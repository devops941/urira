async function seedFoods() {
  try {
    console.log('Connecting to MongoDB...');
    await mongoose.connect(ENV.MONGODB_URI);
    console.log('Connected! Checking existing food collection...');

    for (const food of INITIAL_FOODS) {
      await Food.findOneAndUpdate(
        { normalizedName: food.normalizedName },
        { $set: food },
        { upsert: true, new: true }
      );
    }

    const count = await Food.countDocuments();
    console.log(`Successfully seeded verified food records! Total verified foods in DB: ${count}`);
    await mongoose.disconnect();
    process.exit(0);
  } catch (error) {
    console.error('Failed to seed foods:', error);
    process.exit(1);
  }
}

if (import.meta.url.endsWith(process.argv[1]) || process.argv[1]?.includes('seed-foods')) {
  seedFoods();
}
